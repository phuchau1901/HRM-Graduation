// Build the project's dependency-free classic-script distribution for file://.
// Source modules stay separate for development and Node tests.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import vm from 'node:vm';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const modules=[
 'api/client.js','utils.js','data/seed.js','data/document-content.js','permissions.js',
 'store.js','components/ui.js','components/dialog.js','pages/dashboard.js',
 'pages/attendance-report.js','pages/roles.js','pages/users.js','pages/work.js','pages/operations.js','router.js',
 'actions.js','app.js'
];
const handbook=await readFile(path.join(root,'assets/documents/intelex-handbook.md'),'utf8');
await writeFile(path.join(root,'assets/js/data/document-content.js'),
 '// Generated by scripts/build-browser.js from assets/documents/.\n'+
 'export const DOCUMENT_CONTENTS='+JSON.stringify({'assets/documents/intelex-handbook.md':handbook},null,2)+';\n');

const chunks=[];
for(const file of modules){
 let source=await readFile(path.join(root,'assets/js',file),'utf8');
 // This project's imports only share identically named bindings, the state
 // alias `s`, and the permissions namespace `scope`. Fail on new alias forms.
 for(const [,clause] of source.matchAll(/^import\s+(.+?)\s+from\s+['"][^'"]+['"];?\r?$/gm)){
  if(clause.includes(' as ')&&clause!=='* as scope'&&!/^\{state as s[,}]/.test(clause)){
   throw Error('Unsupported import alias in '+file+': '+clause);
  }
 }
 source=source.replace(/^import\s+.+?\s+from\s+['"][^'"]+['"];?\r?\n/gm,'')
  .replace(/^export\s+(?=(?:const|let|function|async function|class)\b)/gm,'');
 chunks.push('// Source: '+file+'\n'+source);
 if(file==='permissions.js')chunks.push('const scope=Object.freeze({scopedTeams,employees,projects,tasks,documents,requests,can,routeAllowed});');
 if(file==='store.js')chunks.push('const s=state;');
}
const bundle='// Generated file. Edit source modules, then run node scripts/build-browser.js.\n(()=>{\n"use strict";\n'+chunks.join('\n\n')+'\n})();\n';
// Catch duplicate declarations or unsupported syntax before replacing the build.
new vm.Script(bundle,{filename:'erp-browser.js'});
await mkdir(path.join(root,'assets/js/dist'),{recursive:true});
await writeFile(path.join(root,'assets/js/dist/erp-browser.js'),bundle);
console.log('Built assets/js/dist/erp-browser.js ('+Buffer.byteLength(bundle)+' bytes)');
